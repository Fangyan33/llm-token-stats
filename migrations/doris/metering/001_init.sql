    "dynamic_partition.prefix" = "p",
    "dynamic_partition.buckets" = "16",
    "dynamic_partition.create_history_partition" = "true",
    "dynamic_partition.time_zone" = "UTC"
);

-- Retain conflict markers: one variant may expire before another.
CREATE TABLE IF NOT EXISTS metering.request_conflict_ids (
    logical_request_id VARCHAR(36) NOT NULL COMMENT 'Observer 为一次观察生成的规范 UUIDv4；请求级主标识及 Kafka key',
    detected_at DATETIME(3) NOT NULL COMMENT 'Consumer 发现冲突或消费缺口的 UTC 时间'
)
UNIQUE KEY(logical_request_id)
COMMENT '请求级持久冲突标记表；证据过期后仍阻止冲突请求重新进入有效统计'
DISTRIBUTED BY HASH(logical_request_id) BUCKETS 16
PROPERTIES ("replication_num" = "1", "enable_unique_key_merge_on_write" = "true");

CREATE TABLE IF NOT EXISTS metering.ingest_rejections (
    kafka_record_date DATE NOT NULL COMMENT 'Kafka 消息时间戳对应的 UTC 日期，用于拒收诊断分区及保留',
    kafka_topic VARCHAR(249) NOT NULL COMMENT '事件或处理证据所属的 Kafka topic 名称',
    kafka_partition INT NOT NULL COMMENT 'Kafka 分区编号，offset 只在同一 topic 和分区内比较',
    kafka_offset BIGINT NOT NULL COMMENT '消息在 Kafka 分区内的 offset，0 是有效位置',
    payload_hash CHAR(64) NOT NULL COMMENT '被拒收的原始 Kafka value 字节的 SHA-256，仅保存摘要而不保存原始消息',
    reason VARCHAR(64) NOT NULL COMMENT '固定原因码，不包含原始消息、密钥或任意错误文本',
    kafka_record_at DATETIME(3) NOT NULL COMMENT 'Kafka 消息时间戳对应的 UTC 时间，不替代请求开始时间',
    ingested_at DATETIME(3) NOT NULL COMMENT 'Consumer 冻结批次的入库审计时间，UTC，不作为请求统计日期'
)
UNIQUE KEY(kafka_record_date, kafka_topic, kafka_partition, kafka_offset, payload_hash)
COMMENT 'Kafka 消息拒收诊断表；仅保存来源坐标、摘要及固定原因，不保存原始消息'
PARTITION BY RANGE(kafka_record_date) ()
DISTRIBUTED BY HASH(kafka_topic, kafka_partition) BUCKETS 8
PROPERTIES (
    "replication_num" = "1",
    "enable_unique_key_merge_on_write" = "true",
    "dynamic_partition.enable" = "true",
    "dynamic_partition.time_unit" = "DAY",
    "dynamic_partition.start" = "-364",
    "dynamic_partition.end" = "2",
    "dynamic_partition.prefix" = "p",
    "dynamic_partition.buckets" = "8",
    "dynamic_partition.create_history_partition" = "true",
    "dynamic_partition.time_zone" = "UTC"
);

