    reasoning_tokens BIGINT NULL COMMENT '输出中的推理 token 子项；NULL 表示未知，0 表示服务报告的有效零值；子项不与父项重复相加',
    reasoning_tokens_source VARCHAR(16) NULL COMMENT '输出中的推理 token 子项的来源：reported 或 unknown；开始事件为 NULL，不实现估算',
    reported_total_tokens BIGINT NULL COMMENT '服务单独上报的总 token 数；NULL 表示未知，0 表示服务报告的有效零值；子项不与父项重复相加',
    reported_total_tokens_source VARCHAR(16) NULL COMMENT '服务单独上报的总 token 数的来源：reported 或 unknown；开始事件为 NULL，不实现估算',
    raw_usage_json STRING NOT NULL COMMENT '仅含白名单数字用量字段的规范 JSON，不含正文或密钥；最多 4096 字节',
