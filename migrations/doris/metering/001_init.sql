    event_created_at_ms BIGINT NOT NULL COMMENT 'Observer 创建此事件的 Unix 毫秒时间，不作为请求统计日期',
    request_model VARCHAR(1024) NULL COMMENT '请求正文中可靠提取的模型名或 ID；未取得或非法时为 NULL',
    response_model VARCHAR(1024) NULL COMMENT '响应上报的模型名或 ID，可能不同于请求模型；未取得或非法时为 NULL',
    http_status SMALLINT NULL COMMENT '网关可见的 HTTP 响应状态码；未知或开始事件为 NULL',
    upstream_attempt_count INT NULL COMMENT '网关可靠取得的上游尝试次数；未知为 NULL，不据此推算隐藏消耗',
    response_flags STRING NULL COMMENT '白名单内的网关响应标志；未可靠取得或未登记时为 NULL',
    response_code_details STRING NULL COMMENT '白名单内的网关响应诊断码；不保存任意错误文本，未知为 NULL',
    business_outcome VARCHAR(32) NULL COMMENT '有没有观察到响应完整结束？response_complete、stream_incomplete 或 unknown；start 为 NULL',
    terminal_observed TINYINT NOT NULL COMMENT '是否收到有效网关 End：1 是、0 否；为 0 时请求结束时间必须为 NULL',
