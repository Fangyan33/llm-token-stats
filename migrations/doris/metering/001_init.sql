-- Phase 1: 365 UTC request dates online (today + previous 364), partitioned by day.
-- Doris dynamic partitions own creation and expiration; archive is an optional future design.
-- Apache Doris 4.1.3 schema. Set the SQL session time zone to UTC.
-- This single-BE example uses one replica. Size buckets and replicas for production.
CREATE DATABASE IF NOT EXISTS metering;

-- Same event_id + same payload_hash is a replay. A different hash remains a variant.
CREATE TABLE IF NOT EXISTS metering.events_raw (
    request_date DATE NOT NULL COMMENT 'UTC 请求日期，由 request_started_at_ms 换算，不由事件到达时间或 UUID 推导',
    logical_request_id VARCHAR(36) NOT NULL COMMENT 'Observer 为一次观察生成的规范 UUIDv4；请求级主标识及 Kafka key',
    event_id VARCHAR(42) NOT NULL COMMENT '事件标识，逻辑请求 ID 加 :start 或 :usage；同 ID 不同内容属于冲突',
    payload_hash CHAR(64) NOT NULL COMMENT '当前规范事件 JSON 的 SHA-256；与事件 ID 共同保留内容变体并实现幂等',
    schema_version INT NOT NULL COMMENT '唯一事件契约版本，当前为 1；未知版本由 Consumer 暂停对应分区',
    event_type VARCHAR(32) NOT NULL COMMENT '事件类型：request_started 或 usage_observed；两者合计仍是一次请求',
    x_request_id VARCHAR(128) NULL COMMENT '网关可见的 X-Request-Id，仅辅助关联；可空、可重复，不用于授权或去重',
    observation_id VARCHAR(36) NOT NULL COMMENT '观察标识，当前与 logical_request_id 相同',
    observation_scope VARCHAR(32) NOT NULL COMMENT '观察范围，当前固定 gateway_response，不代表所有隐藏的上游尝试',
    producer_id VARCHAR(128) NOT NULL COMMENT '生成此事件的 Observer 实例标识，部署时使用实际 Pod UID',
    gateway_instance_id VARCHAR(128) NOT NULL COMMENT '观察请求的网关实例标识，新版为命名空间/Pod名称，历史值可能为Pod UID',
    config_version VARCHAR(128) NOT NULL COMMENT '请求开始时冻结的采集配置版本，需在 Observer 和 Consumer 登记',
    adapter_id VARCHAR(64) NOT NULL COMMENT '响应协议适配器，当前为 chat_completions_v1',
    route_name VARCHAR(128) NOT NULL COMMENT '实际 Envoy HTTP 路由名，不可读时为 unknown；仅诊断，不代表 VirtualService 或归属',
    request_host VARCHAR(253) NULL COMMENT '规范入口 DNS 域名；转小写并去端口及末尾根点，非法输入为 NULL',
    cluster_name VARCHAR(128) NOT NULL COMMENT 'Observer 配置固定的集群名称，业务请求不能覆盖',
    deployment_environment VARCHAR(16) NOT NULL COMMENT 'Observer 固定部署环境：prd、stg 或 dev',
    mapping_status VARCHAR(32) NOT NULL COMMENT '服务解析状态：mapped、unknown_host、invalid_host、lookup_not_implemented、lookup_timeout、lookup_unavailable、lookup_invalid_response、lookup_overloaded、lookup_rate_limited；空 URI 为未实现占位，配置 HTTP/HTTPS 可解析',
    mapping_version CHAR(64) NULL COMMENT '成功服务解析快照的规范 SHA-256，绑定 Host、集群、环境及服务和供应商；未知为 NULL',
    customer_mapping_status VARCHAR(32) NOT NULL COMMENT '客户解析状态：mapped、unknown_api_key、invalid_api_key、lookup_not_implemented、lookup_timeout、lookup_unavailable、lookup_invalid_response、lookup_overloaded、lookup_rate_limited；空 URI 为未实现占位，配置 HTTP/HTTPS 可解析',
    customer_mapping_version CHAR(64) NULL COMMENT '成功客户解析快照的规范 SHA-256，绑定部署上下文、API Key ID 和客户；未知为 NULL',
    service_id VARCHAR(128) NULL COMMENT '服务接口返回的服务 ID；未实现或失败为 NULL，不使用默认服务补值',
    service_name VARCHAR(512) NULL COMMENT '请求发生时的服务名称快照；解析未知时为 NULL，不用最新名称覆盖历史',
    provider_name VARCHAR(512) NULL COMMENT '请求发生时的供应商名称快照；解析未知时为 NULL，不用最新名称覆盖历史',
    customer_name VARCHAR(512) NULL COMMENT '请求发生时的客户名称快照；解析未知时为 NULL，不用最新名称覆盖历史',
    api_key_id VARCHAR(128) NULL COMMENT '客户接口返回的稳定 API Key ID；未知为 NULL，绝不是原始 Bearer token',
    customer_id VARCHAR(128) NULL COMMENT '与 api_key_id 同次成功解析得到的客户 ID；未知为 NULL，不采信客户端自报 ID',
    provider_id VARCHAR(128) NULL COMMENT '服务接口返回的服务所属供应商 ID；未知为 NULL，不代表隐藏的实际执行方',
    identity_status VARCHAR(16) NOT NULL COMMENT '客户归属状态：known 或 invalid；仅完整客户解析成功为 known，不表示鉴权判定',
    identity_hash CHAR(64) NOT NULL COMMENT '固定十五项归属与部署快照元组的规范 SHA-256，不含原始密钥或诊断路由',
    request_started_at_ms BIGINT NOT NULL COMMENT '网关观察到请求头的 Unix 毫秒时间；决定 UTC 统计日期',
